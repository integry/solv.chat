import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const engineRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspaceRoot = path.resolve(engineRoot, "../..");
const adminDistDir = path.join(workspaceRoot, "packages/admin/dist");
const indexHtmlPath = path.join(adminDistDir, "index.html");
const outPath = path.join(engineRoot, "src/adminBundle.ts");

if (!existsSync(indexHtmlPath) || process.argv.includes("--rebuild")) {
  execFileSync("npm", ["run", "build", "-w", "@solvchat/core", "--if-present"], {
    cwd: workspaceRoot,
    stdio: "inherit",
  });
  execFileSync("npm", ["run", "build", "-w", "@solvchat/admin"], {
    cwd: workspaceRoot,
    stdio: "inherit",
  });
}

const MIME_TYPES = {
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
};

function collectFiles(dir) {
  if (!existsSync(dir)) return [];
  const entries = readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectFiles(full));
    } else if (entry.isFile()) {
      files.push(full);
    }
  }
  return files;
}

const html = readFileSync(indexHtmlPath, "utf8");
const assets = {};

for (const file of collectFiles(adminDistDir)) {
  if (file === indexHtmlPath) continue;
  const rel = path.relative(adminDistDir, file).split(path.sep).join("/");
  const ext = path.extname(file).toLowerCase();
  const type = MIME_TYPES[ext] ?? "application/octet-stream";
  assets[`/admin/${rel}`] = {
    body: readFileSync(file, "utf8"),
    type,
  };
}

const content = `// Generated by scripts/sync-admin.mjs — do not edit by hand.\nexport const ADMIN_HTML = ${JSON.stringify(html)};\nexport const ADMIN_ASSETS: Record<string, { body: string; type: string }> = ${JSON.stringify(assets)};\n`;
writeFileSync(outPath, content, "utf8");
