import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const engineRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspaceRoot = path.resolve(engineRoot, "../..");
const widgetBundlePath = path.join(workspaceRoot, "packages/widget/dist/widget.js");
const bootPath = path.join(workspaceRoot, "packages/widget/dist/boot.js");
const outPath = path.join(engineRoot, "src/widgetBundle.ts");

if (!existsSync(widgetBundlePath) || !existsSync(bootPath) || process.argv.includes("--rebuild")) {
  execFileSync("npm", ["run", "build", "-w", "@solvchat/core", "--if-present"], {
    cwd: workspaceRoot,
    stdio: "inherit",
  });
  execFileSync("npm", ["run", "build", "-w", "@solvchat/widget"], {
    cwd: workspaceRoot,
    stdio: "inherit",
  });
}

const bundle = readFileSync(widgetBundlePath, "utf8");
const boot = readFileSync(bootPath, "utf8");
const hash = createHash("sha256").update(boot).digest("base64");
const content = `// Generated by scripts/sync-widget.mjs — do not edit by hand.
export const WIDGET_BUNDLE = ${JSON.stringify(bundle)};
export const WIDGET_BOOT = ${JSON.stringify(boot)};
export const WIDGET_BOOT_HASH = ${JSON.stringify(`'sha256-${hash}'`)};
`;
writeFileSync(outPath, content, "utf8");
